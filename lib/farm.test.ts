import assert from 'node:assert/strict';
import {accrue,harvest,upgrade} from '../lib/farm.ts';
const f={balance:0,stored:0,updated:1000,level:0};
assert.equal(accrue(f,61000).stored,6);
assert.equal(accrue(f,9999999).stored,20);
assert.equal(accrue(f,0).stored,0);
assert.equal(harvest({...f,stored:6.7},1000).balance,6);
assert.ok(Math.abs(harvest({...f,stored:6.7},1000).stored-.7)<.00001);
assert.equal(upgrade({...f,balance:19},1000).level,0);
const u=upgrade({...f,balance:20},61000);
assert.equal(u.level,1);assert.equal(u.balance,0);assert.equal(u.stored,6);
assert.equal(accrue(u,121000).stored,18);
assert.equal(upgrade({...f,level:3,balance:999},1000).level,3);
console.log('9 economy checks passed');
